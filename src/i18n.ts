export function resolveLocale(preferences: readonly string[]): Locale {
  for (const preference of preferences) {
    const code = preference.toLowerCase().split(/[-_]/)[0]!;
    if (Object.hasOwn(languages, code)) return code as Locale;
  }
  return "en";
}
export function localizeAnswer(answer: Answer, locale: Locale): string {
  return translations[locale].answers[ANSWERS.indexOf(answer)] ?? answer;
}
